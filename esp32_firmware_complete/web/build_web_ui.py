"""
Generate ../web_ui.h from index.html (gzip-compressed byte array in flash).

Run after editing index.html:
    python esp32_firmware_complete/web/build_web_ui.py

The ESP32 serves the bytes as-is with "Content-Encoding: gzip", so the page
costs ~1/4 of its size in flash and no RAM to decompress.
"""
import gzip
import pathlib

here = pathlib.Path(__file__).resolve().parent
html = (here / "index.html").read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)  # mtime=0: stable output

lines = []
for i in range(0, len(gz), 20):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")

header = f"""// GENERATED by web/build_web_ui.py from web/index.html - do not edit.
// {len(html)} bytes HTML -> {len(gz)} bytes gzip
#pragma once
#include <Arduino.h>

const size_t WEB_UI_GZ_LEN = {len(gz)};
const uint8_t WEB_UI_GZ[] PROGMEM = {{
{chr(10).join(lines)}
}};
"""
(here.parent / "web_ui.h").write_text(header, encoding="utf-8", newline="\n")
print(f"web_ui.h: {len(html)} bytes -> {len(gz)} bytes gzip")
