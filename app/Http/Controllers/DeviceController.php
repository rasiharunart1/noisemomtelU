<?php

namespace App\Http\Controllers;

use App\Models\Device;
use App\Models\FftLog;
use App\Models\AudioRecording;
use Illuminate\Http\Request;
use App\Models\Setting;
use Illuminate\Support\Str;
use Illuminate\Support\Facades\Storage;
use App\Services\DeviceCommandService;
use ZipArchive;

class DeviceController extends Controller
{
    /**
     * Display a listing of devices
     */
    public function index()
    {
        $devices = Device::withCount('fftLogs')
            ->orderBy('device_id')
            ->get();

        return view('devices.index', compact('devices'));
    }

    /**
     * Show the form for creating a new device
     */
    public function create()
    {
        return view('devices.create');
    }

    /**
     * Store a newly created device
     */
    /**
     * Store a newly created device
     */
    public function store(Request $request)
    {
        $validated = $request->validate([
            'name' => 'required|string|max:255',
            'description' => 'nullable|string',
            'latitude' => 'nullable|numeric|between:-90,90',
            'longitude' => 'nullable|numeric|between:-180,180',
        ]);

        // Generate Unique Device ID
        do {
            $uniqueId = strtoupper(Str::random(6));
            $deviceId = 'ESP32-' . $uniqueId;
        } while (Device::where('device_id', $deviceId)->exists());

        // Auto-generate topic based on default pattern
        // Pattern: audio/{DEVICE_ID}/data
        $mqttTopic = "audio/{$deviceId}/data";

        $device = Device::create([
            'id' => Str::uuid(),
            'device_id' => $deviceId,
            'name' => $validated['name'],
            'description' => $validated['description'] ?? null,
            'mqtt_topic' => $mqttTopic,
            'status' => 'offline',
            'latitude' => $validated['latitude'] ?? null,
            'longitude' => $validated['longitude'] ?? null,
            // Token will be auto-generated by Model Boot
        ]);

        return redirect()->route('devices.show', $device)
            ->with('success', "Device created! ID: {$deviceId}");
    }

    /**
     * Show the specified device with realtime data
     */
    public function show(Device $device)
    {
        $recentLogs = $device->fftLogs()
            ->orderBy('created_at', 'desc')
            ->limit(100)
            ->get();

        $recordings = $device->recordings()
            ->orderBy('created_at', 'desc')
            ->get();

        $schedules = $device->schedules()
            ->orderBy('start_time', 'asc')
            ->get();

        return view('devices.show', compact('device', 'recentLogs', 'recordings', 'schedules'));
    }

    /**
     * Show the form for editing the device
     */
    public function edit(Device $device)
    {
        return view('devices.edit', compact('device'));
    }

    /**
     * Update the specified device
     */
    public function update(Request $request, Device $device)
    {
        $validated = $request->validate([
            'name' => 'required|string|max:255',
            'description' => 'nullable|string',
            'latitude' => 'nullable|numeric|between:-90,90',
            'longitude' => 'nullable|numeric|between:-180,180',
        ]);

        $device->update([
            'name' => $validated['name'],
            'description' => $validated['description'],
            'latitude' => $validated['latitude'] ?? null,
            'longitude' => $validated['longitude'] ?? null,
        ]);

        return redirect()->route('devices.show', $device)
            ->with('success', 'Device updated successfully.');
    }

    /**
     * Remove the specified device
     */
    public function destroy(Device $device)
    {
        $device->delete();

        return redirect()->route('devices.index')
            ->with('success', 'Device deleted successfully.');
    }

    /**
     * API endpoint for realtime device data
     */
    public function realtimeData(Device $device)
    {
        $latestLog = $device->fftLogs()
            ->latest('created_at')
            ->first();

        return response()->json([
            'device_id' => $device->device_id,
            'status' => $device->status,
            'last_seen' => $device->last_seen?->toIso8601String(),
            'latest_data' => $latestLog,
        ]);
    }

    /**
     * Update device gain (multiplier)
     */
    public function updateGain(Request $request, Device $device)
    {
        $request->validate([
            'gain' => 'required|numeric|between:0.1,50.0'
        ]);

        $device->update([
            'gain' => $request->gain
        ]);

        return response()->json([
            'success' => true,
            'gain' => $device->gain
        ]);
    }

    /**
     * Update device threshold
     */
    public function updateThreshold(Request $request, Device $device)
    {
        $request->validate([
            'threshold' => 'required|numeric|between:30,120'
        ]);

        $device->update([
            'max_db_spl_threshold' => $request->threshold
        ]);

        return response()->json([
            'success' => true,
            'threshold' => $device->max_db_spl_threshold
        ]);
    }

    public function startRecording(Request $request, Device $device)
    {
        $validated = $request->validate([
            'duration' => 'nullable|integer|min:5|max:14400', // seconds, up to 4 hours
        ]);

        $duration = (int) ($validated['duration'] ?? 0);

        return $this->sendCommand($device, 'start_recording', [
            'duration' => $duration,
        ]);
    }

    public function stopRecording(Request $request, Device $device)
    {
        return $this->sendCommand($device, 'stop_recording');
    }

    /**
     * Ask the device to upload a recording that is still on its SD card.
     * The device publishes upload progress on its recording_status topic.
     */
    public function requestRecording(Request $request, Device $device, AudioRecording $recording)
    {
        if ($recording->device_id !== $device->id) {
            return response()->json([
                'success' => false,
                'message' => 'Recording does not belong to this device'
            ], 403);
        }

        if ($recording->status === 'completed') {
            return response()->json([
                'success' => true,
                'message' => 'Recording already uploaded',
                'status' => 'completed'
            ]);
        }

        if (empty($recording->sd_filename)) {
            return response()->json([
                'success' => false,
                'message' => 'Recording has no SD card filename'
            ], 400);
        }

        $recording->update(['status' => 'requested']);

        return $this->sendCommand($device, 'upload_file', [
            'filename' => $recording->sd_filename,
        ]);
    }

    /**
     * Poll the current status of a recording (used by the UI while waiting
     * for an on-demand upload to finish).
     */
    public function recordingStatus(Device $device, AudioRecording $recording)
    {
        if ($recording->device_id !== $device->id) {
            return response()->json([
                'success' => false,
                'message' => 'Recording does not belong to this device'
            ], 403);
        }

        $recording->refresh();

        return response()->json([
            'success' => true,
            'status' => $recording->status,
            'uploaded_at' => $recording->uploaded_at,
            'file_size_bytes' => $recording->file_size_bytes,
            'path' => $recording->path,
            'download_url' => $recording->status === 'completed'
                ? route('recordings.download', $recording)
                : null,
        ]);
    }

    /**
     * SD card / maintenance commands for the device:
     *  upload_all      upload every recording not yet on the server (force: re-upload all)
     *  list_files      device reports its SD files; the listener syncs the table
     *  get_status      device publishes a fresh health report
     *  delete_uploaded delete recordings that are already on the server from the SD card
     *  set_auto_upload enable/disable automatic upload after each recording
     *  restart         reboot the device (an active recording is closed first)
     */
    public function command(Request $request, Device $device)
    {
        $validated = $request->validate([
            'action' => 'required|string|in:upload_all,list_files,get_status,delete_uploaded,set_auto_upload,restart',
            'force' => 'sometimes|boolean',
            'enabled' => 'sometimes|boolean',
        ]);

        $data = match ($validated['action']) {
            'upload_all' => ['force' => (bool) ($validated['force'] ?? false)],
            'set_auto_upload' => ['enabled' => (bool) ($validated['enabled'] ?? true)],
            default => [],
        };

        return $this->sendCommand($device, $validated['action'], $data);
    }

    public function resetWifi(Request $request, Device $device)
    {
        return $this->sendCommand($device, 'reset_wifi');
    }

    public function updateWifi(Request $request, Device $device)
    {
        // SSID is optional: leave it empty to only change the upload server
        // (the device then keeps its WiFi and does not restart).
        $validated = $request->validate([
            'ssid' => 'nullable|string|max:32',
            'password' => 'nullable|required_with:ssid|string|max:64',
            // Domain (e.g. dev.nhmedia.pro) or IP, without http:// or a path
            'server_ip' => ['required', 'string', 'max:63', 'regex:/^[A-Za-z0-9.\-]+$/'],
            'server_port' => 'required|integer|min:1|max:65535',
        ], [
            'server_ip.regex' => 'Server host must be a domain or IP only (no http:// or /path).',
        ]);

        $data = [
            'server_ip' => strtolower($validated['server_ip']),
            'server_port' => (int) $validated['server_port'],
        ];
        if (!empty($validated['ssid'])) {
            $data['ssid'] = $validated['ssid'];
            $data['password'] = $validated['password'];
        }

        return $this->sendCommand($device, 'update_wifi', $data);
    }

    private function sendCommand(Device $device, string $action, array $data = [])
    {
        try {
            app(DeviceCommandService::class)->send($device->device_id, $action, $data);

            return response()->json([
                'success' => true,
                'message' => "Command {$action} sent to {$device->device_id}"
            ]);
        } catch (\Exception $e) {
            return response()->json([
                'success' => false,
                'message' => 'Failed to send command: ' . $e->getMessage()
            ], 500);
        }
    }

    /**
     * Download a single audio recording
     */
    public function downloadRecording(AudioRecording $recording)
    {
        // Recordings that are only on the SD card have an empty path
        $disk = Storage::disk('public');
        if (empty($recording->path) || !$disk->exists($recording->path)) {
            return redirect()->back()->with('error', 'Audio file is not on the server yet. Use "Fetch from Device" first.');
        }
        $filePath = $disk->path($recording->path);

        return response()->download($filePath, $recording->filename);
    }

    /**
     * Bulk download multiple recordings as ZIP
     */
    public function bulkDownload(Request $request)
    {
        $request->validate([
            'recording_ids' => 'required|array',
            'recording_ids.*' => 'exists:audio_recordings,id'
        ]);

        $recordings = AudioRecording::whereIn('id', $request->recording_ids)->get();

        if ($recordings->isEmpty()) {
            return redirect()->back()->with('error', 'No recordings found');
        }

        // Create temporary ZIP file
        $zipFileName = 'recordings_' . time() . '.zip';
        $zipFilePath = storage_path('app/temp/' . $zipFileName);
        
        // Ensure temp directory exists
        if (!file_exists(storage_path('app/temp'))) {
            mkdir(storage_path('app/temp'), 0755, true);
        }

        $zip = new ZipArchive;
        
        if ($zip->open($zipFilePath, ZipArchive::CREATE | ZipArchive::OVERWRITE) === TRUE) {
            $added = 0;
            foreach ($recordings as $recording) {
                if (empty($recording->path)) {
                    continue; // still only on the SD card
                }
                $filePath = storage_path('app/public/' . $recording->path);

                if (is_file($filePath)) {
                    $zip->addFile($filePath, $recording->filename);
                    $added++;
                }
            }
            $zip->close();

            if ($added === 0) {
                @unlink($zipFilePath);
                return redirect()->back()->with('error', 'None of the selected recordings are stored on the server yet');
            }

            return response()->download($zipFilePath, $zipFileName)->deleteFileAfterSend(true);
        }

        return redirect()->back()->with('error', 'Failed to create ZIP file');
    }
}
